// Dev-only generator. Not shipped in the APK: it writes a Kotlin table that the app commits.
//
//   npm install --prefix tools/palette
//   node tools/palette/generate.mjs
//
// Reads the brand colours straight from RadioRepository.kt, so there is no second list to keep in
// sync; the StationPaletteTest fails if a station has no generated palette.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Hct, SchemeTonalSpot, MaterialDynamicColors as M, hexFromArgb, argbFromHex } from '@material/material-color-utilities';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const repositoryPath = join(root, 'app/src/main/java/lt/radijas/tv/data/repository/RadioRepository.kt');
const outputPath = join(root, 'app/src/main/java/lt/radijas/tv/ui/theme/StationPalette.kt');

const source = readFileSync(repositoryPath, 'utf8');
const stationPattern = /id = "([a-z0-9]+)"[\s\S]*?brandColor = 0x([0-9A-Fa-f]{8})L/g;
const stations = [...source.matchAll(stationPattern)].map(([, id, argb]) => ({ id, argb }));
if (stations.length !== 11) {
  throw new Error(`expected 11 stations in RadioRepository.kt, parsed ${stations.length}: ${stations.map(s => s.id)}`);
}

const linearize = (c) => {
  const v = c / 255;
  return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
};
const luminance = (argb) =>
  0.2126 * linearize((argb >>> 16) & 0xff) +
  0.7152 * linearize((argb >>> 8) & 0xff) +
  0.0722 * linearize(argb & 0xff);
const contrast = (a, b) => {
  const la = luminance(a), lb = luminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
};
/** Same 8 % elevation tint the tile applies at rest; keep in sync with StationTile.TILE_REST_TINT. */
const TILE_REST_TINT = 0.08;

const lerp = (a, b, t) => {
  const channel = (shift) => Math.round(((a >>> shift) & 0xff) + (((b >>> shift) & 0xff) - ((a >>> shift) & 0xff)) * t);
  return (0xff << 24) | (channel(16) << 16) | (channel(8) << 8) | channel(0);
};

const lighten = (argb, k) => {
  const channel = (shift) => Math.round(((argb >>> shift) & 0xff) + (255 - ((argb >>> shift) & 0xff)) * k);
  return (0xff << 24) | (channel(16) << 16) | (channel(8) << 8) | channel(0);
};

// The focus ring is read against the page and against the focused tile (6:1), and against the
// resting tile it borders (4.5:1 is enough there: a 6:1 ring over a mid-grey fill would have to be
// almost white and would lose the station hue).
function borderFor(primary, { surface, primaryContainer, rest }) {
  for (let k = 0; k <= 0.30; k += 0.01) {
    const candidate = lighten(primary, k);
    if (contrast(candidate, surface) >= 6 && contrast(candidate, primaryContainer) >= 6 &&
        contrast(candidate, rest) >= 4.5) return candidate;
  }
  throw new Error(`no border shade works for primary ${hexFromArgb(primary)}`);
}

const role = (scheme, name) => M[name].getArgb(scheme);
const hex = (argb) => '0xFF' + hexFromArgb(argb).slice(1).toUpperCase();

const rows = stations.map(({ id, argb }) => {
  const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex('#' + argb.slice(2))), true, 0.0);
  const surface = role(scheme, 'surface');
  const surfaceVariant = role(scheme, 'surfaceVariant');
  const primaryContainer = role(scheme, 'primaryContainer');
  const primary = role(scheme, 'primary');
  const rest = lerp(surfaceVariant, primary, TILE_REST_TINT);
  const border = borderFor(primary, { surface, primaryContainer, rest });
  const values = {
    primary: role(scheme, 'primary'),
    onPrimary: role(scheme, 'onPrimary'),
    primaryContainer,
    onPrimaryContainer: role(scheme, 'onPrimaryContainer'),
    surface,
    onSurface: role(scheme, 'onSurface'),
    surfaceVariant,
    onSurfaceVariant: role(scheme, 'onSurfaceVariant'),
    border,
  };
  const args = Object.entries(values).map(([name, value]) => `        ${name} = ${hex(value)},`).join('\n');
  return `    "${id}" to StationColors(\n${args}\n    ),`;
});

const file = `// Generated by tools/palette/generate.mjs from RadioRepository.kt brand colours.
// Do not edit by hand: change the station colour, then run the generator again.
package lt.radijas.tv.ui.theme

/** M3 roles the app paints with. Colours are ARGB longs; the theme converts them to [androidx.compose.ui.graphics.Color]. */
internal data class StationColors(
    val primary: Long,
    val onPrimary: Long,
    val primaryContainer: Long,
    val onPrimaryContainer: Long,
    val surface: Long,
    val onSurface: Long,
    val surfaceVariant: Long,
    val onSurfaceVariant: Long,
    val border: Long,
)

internal val stationColors: Map<String, StationColors> = mapOf(
${rows.join('\n')}
)
`;

writeFileSync(outputPath, file);
console.log(`wrote ${stations.length} palettes to ${outputPath}`);
